#!/bin/sh
set -eu

config=/var/lib/devassistant/runtime/collector-runtime.yaml
attempt=0
while [ ! -s "$config" ] && [ "$attempt" -lt 120 ]; do
  attempt=$((attempt + 1))
  sleep 1
done

if [ ! -s "$config" ]; then
  echo "Runtime Collector configuration was not generated by python-api" >&2
  exit 1
fi

exec /usr/local/bin/devassistant-otelcol --config="$config"
