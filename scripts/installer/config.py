"""Generate local HTTPS configuration while preserving existing identities."""
from __future__ import annotations

import json
import hashlib
import re
import secrets
from pathlib import Path
from urllib.parse import quote

from state import ROOT, STATE, atomic, env_read, env_update, load, private_dir, save

SERVICES = {
    "app": ("web:3000", "3000"), "keycloak": ("keycloak:8080", "8080"),
    "qdrant": ("qdrant:6333", "6333"), "neo4j": ("neo4j:7474", "7474"),
    "minio": ("minio:9001", "9001"), "s3": ("minio:9000", "9000"),
    "uploads": ("tusd:1080", "1080"), "outline": ("outline:3000", "3000"),
    "drawio": ("drawio:8080", "8080"), "sonarqube": ("sonarqube:9000", "9000"),
}
OPTIONAL = {"outline", "drawio", "sonarqube"}
MARKER = "# Generated by Developer Assistant installer.\n"


def defaults() -> dict:
    return {"schema": 1, "optional": [], "models": ["bge-m3", "gemma3:4b"],
            "bolt_port": 7687, "grpc_port": 6334,
            "hosts": {name: {"hostname": name + ".localhost.dev", "port": 443} for name in SERVICES}}


def validate(choices: dict) -> dict:
    if choices.get("schema") != 1 or set(choices.get("optional", [])) - OPTIONAL:
        raise ValueError("Unsupported installer choices")
    if (not isinstance(choices.get("models"), list) or not choices["models"] or
            any(not isinstance(m, str) or not re.fullmatch(r"[a-zA-Z0-9][a-zA-Z0-9._:/-]*", m) for m in choices["models"])):
        raise ValueError("Invalid Ollama model name")
    endpoints = set()
    for name in SERVICES:
        entry = choices["hosts"][name]
        hostname = entry["hostname"]
        if (len(hostname) > 253 or "." not in hostname or
                not all(re.fullmatch(r"[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?", p) for p in hostname.split("."))):
            raise ValueError(f"Invalid hostname for {name}; use a lowercase DNS hostname")
        port = entry["port"]
        if type(port) is not int or not 1 <= port <= 65535:
            raise ValueError(f"Invalid port for {name}")
        endpoint = (hostname, port)
        if endpoint in endpoints:
            raise ValueError("Two services cannot have the same hostname and port")
        endpoints.add(endpoint)
    public = {choices["hosts"][name]["port"] for name in selected(choices)}
    for key in ("bolt_port", "grpc_port"):
        port = choices[key]
        if type(port) is not int or not 1 <= port <= 65535 or port in public:
            raise ValueError(f"Invalid or conflicting {key}")
    if choices["bolt_port"] == choices["grpc_port"] or (public | {choices["bolt_port"], choices["grpc_port"]}) & {47831, 8765, 11434, 24318, 9443}:
        raise ValueError("Published port conflicts with Runtime, Ollama or another service")
    return choices


def selected(choices: dict) -> list[str]:
    return [name for name in SERVICES if name not in OPTIONAL or name in choices["optional"]]


def url(choices: dict, name: str) -> str:
    entry = choices["hosts"][name]
    return "https://" + entry["hostname"] + (":" + str(entry["port"]) if entry["port"] != 443 else "")


def choose(edit: bool = False) -> dict:
    path = STATE / "choices.json"
    choices = validate(load(path, defaults()))
    if edit or not path.exists():
        if not __import__("sys").stdin.isatty():
            raise ValueError("First install requires a terminal. Create .install/choices.json as documented for headless automation.")
        for name in sorted(OPTIONAL):
            label = "analyzers (SonarQube + mTLS worker)" if name == "sonarqube" else name
            answer = input(f"Install optional {label}? [y/N] ").strip().lower()
            if answer == "y":
                if name not in choices["optional"]:
                    choices["optional"].append(name)
            elif name in choices["optional"]:
                choices["optional"].remove(name)
        for name in selected(choices):
            entry = choices["hosts"][name]
            entry["hostname"] = input(f"{name} hostname [{entry['hostname']}]: ").strip() or entry["hostname"]
            entry["port"] = int(input(f"{name} HTTPS port [{entry['port']}]: ").strip() or entry["port"])
        for key in ("bolt_port", "grpc_port"):
            choices[key] = int(input(f"{key} [{choices[key]}]: ").strip() or choices[key])
        validate(choices)
        save(path, choices)
    return choices


def owned_write(path: Path, content: str) -> None:
    if path.exists() and not path.read_text().startswith(MARKER):
        raise ValueError(f"Existing {path.relative_to(ROOT)} is user-owned; merge it manually before installing")
    atomic(path, MARKER + content)


def generate() -> None:
    choices = validate(load(STATE / "choices.json"))
    # Preflight all files before mutating any configuration.
    for folder in ("api", "web"):
        for name in ("docker-compose.override.yml", "compose.override.yaml", "compose.override.yml", "docker-compose.override.yaml"):
            path = ROOT / folder / name
            if path.exists() and (name != "docker-compose.override.yml" or not path.read_text().startswith(MARKER)):
                raise ValueError(f"Existing {folder}/{name} needs a manual merge")
    api_path, web_path = ROOT / "api/.env", ROOT / "web/.env"
    if api_path.is_symlink() or web_path.is_symlink():
        raise ValueError("Resolve symbolic-link environment files before installing; configuration was not changed")
    api, web = env_read(api_path), env_read(web_path)
    if not api.get("RAG_CALLBACK_SECRET") and web.get("RAG_CALLBACK_SECRET"):
        api["RAG_CALLBACK_SECRET"] = web["RAG_CALLBACK_SECRET"]
    for values, keys in ((api, ["MINIO_ROOT_PASSWORD", "UPLOAD_TOKEN_SECRET", "TUSD_HOOK_SECRET", "DOWNLOAD_TOKEN_SECRET", "RAG_CALLBACK_SECRET", "NEO4J_PASSWORD", "TELEMETRY_CLICKHOUSE_PASSWORD", "ANALYZER_POSTGRES_PASSWORD", "SONARQUBE_ADMIN_PASSWORD"]),
                         (web, ["OIDC_CLIENT_SECRET", "SESSION_SECRET", "KEYCLOAK_ADMIN_PASSWORD", "KEYCLOAK_BOOTSTRAP_PASSWORD", "OUTLINE_SECRET_KEY", "OUTLINE_UTILS_SECRET", "OUTLINE_DATABASE_PASSWORD", "OUTLINE_OIDC_CLIENT_SECRET"])):
        for key in keys:
            # Never replace an existing nonempty value, even a weak bootstrap value.
            if not values.get(key):
                values[key] = secrets.token_hex(32)
    callback = api.get("RAG_CALLBACK_SECRET")
    existing_web = env_read(web_path)
    if existing_web.get("RAG_CALLBACK_SECRET") and existing_web["RAG_CALLBACK_SECRET"] != callback:
        raise ValueError("Existing API/Web RAG_CALLBACK_SECRET values differ; reconcile them explicitly")
    web["RAG_CALLBACK_SECRET"] = callback
    api["MINIO_ROOT_USER"] = api.get("MINIO_ROOT_USER") or "devassistant"
    api["NEO4J_USER"] = api.get("NEO4J_USER") or "neo4j"
    api.setdefault("OLLAMA_EMBED_MODEL", choices["models"][0])
    api.update(WEB_ORIGIN=url(choices, "app"))
    web.setdefault("KEYCLOAK_ADMIN_USERNAME", "admin")
    web.setdefault("OIDC_CLIENT_ID", "developer-assistant-web")
    web.setdefault("OIDC_BOOTSTRAP_ADMIN_SUB", "3ca3f484-5ef2-4c37-a8e8-d55d0cf47fb8")
    web.update(APP_URL=url(choices, "app"), WEB_ORIGIN=url(choices, "app"), SESSION_COOKIE_SECURE="true",
               OIDC_ISSUER=url(choices, "keycloak") + "/realms/developer-assistant",
               OIDC_INTERNAL_ISSUER="http://keycloak:8080/realms/developer-assistant",
               OIDC_REDIRECT_URI=url(choices, "app") + "/api/auth/callback")
    web.setdefault("OLLAMA_MODEL", choices["models"][-1])
    web.setdefault("OLLAMA_EVAL_MODEL", choices["models"][-1])
    if "drawio" in choices["optional"]:
        web["VITE_DRAWIO_ORIGIN"] = url(choices, "drawio")
    api = env_update(api_path, api)
    web = env_update(web_path, web)
    proxy = env_read(STATE / "proxy.env")
    proxy.setdefault("QDRANT_PUBLIC_API_KEY", secrets.token_hex(32))
    env_update(STATE / "proxy.env", proxy)
    make_overrides(choices)
    make_caddy(choices)
    make_realm(choices, web)


def make_realm(choices: dict, web: dict) -> None:
    realm = json.loads((ROOT / "web/keycloak/developer-assistant-realm.json").read_text())
    client = realm["clients"][0]
    client.update(clientId=web["OIDC_CLIENT_ID"], secret="__OIDC_CLIENT_SECRET__",
                  redirectUris=[web["OIDC_REDIRECT_URI"]], webOrigins=[url(choices, "app")])
    for mapper in client.get("protocolMappers", []):
        if mapper.get("protocolMapper") == "oidc-audience-mapper":
            mapper.setdefault("config", {})["included.client.audience"] = web["OIDC_CLIENT_ID"]
    realm["users"][0]["id"] = web["OIDC_BOOTSTRAP_ADMIN_SUB"]
    private_dir(STATE / "realm")
    # This template contains placeholders, never passwords. Keycloak runs as UID 1000.
    atomic(STATE / "realm/developer-assistant-realm.json", json.dumps(realm, indent=2), mode=0o644)


def make_overrides(c: dict) -> None:
    # Compose >=2.24.4 !override replaces ports, preventing accidental HTTP/LAN exposure.
    api = {"services": {name: {"ports": []} for name in ("tusd", "minio", "qdrant", "neo4j")}}
    # An anonymous volume populated from the built image preserves Composer's
    # vendor directory; the development host bind would hide it on a fresh folder.
    api["services"]["python-api"] = {"environment": {"TUS_PUBLIC_URL": url(c, "uploads") + "/files/"},
                                            "volumes": ["/opt/php-cli"]}
    neo = api["services"]["neo4j"]
    neo.update(ports=[f"127.0.0.1:{c['bolt_port']}:7687"], environment={
        "NEO4J_server_bolt_tls__level": "OPTIONAL",  # private API uses bolt; browser uses bolt+s
        "NEO4J_server_bolt_advertised__address": f"{c['hosts']['neo4j']['hostname']}:{c['bolt_port']}",
        "NEO4J_dbms_ssl_policy_bolt_enabled": "true", "NEO4J_dbms_ssl_policy_bolt_base__directory": "/certificates/bolt",
        "NEO4J_dbms_ssl_policy_bolt_private__key": "key.pem", "NEO4J_dbms_ssl_policy_bolt_public__certificate": "cert.pem",
        "NEO4J_dbms_ssl_policy_bolt_client__auth": "NONE"},
        volumes=[f"{STATE}/certs/neo4j:/certificates/bolt:ro"])
    neo["healthcheck"] = {"test": ["CMD-SHELL", 'cypher-shell -u "$${NEO4J_AUTH%%/*}" -p "$${NEO4J_AUTH#*/}" "RETURN 1" >/dev/null']}
    api["services"]["qdrant"]["networks"] = ["default", "devassistant_net"]
    if "sonarqube" in c["optional"]:
        api["services"]["analyzer-worker"] = {"ports": []}
    web = {"services": {name: {"ports": []} for name in ("web", "keycloak", "outline", "drawio")}}
    web["services"]["drawio"]["networks"] = ["devassistant_net"]
    web["services"]["keycloak"].update(environment={"KC_HOSTNAME": url(c, "keycloak"), "KC_PROXY_HEADERS": "xforwarded"},
        volumes=[f"{STATE}/realm/developer-assistant-realm.json:/opt/keycloak/realm-template/developer-assistant-realm.json:ro"])
    # Escape preserved passwords for sed without interpreting shell metacharacters.
    web["services"]["keycloak"]["command"] = [r'''set -e; mkdir -p /opt/keycloak/data/import;
escape() { printf '%s' "$$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/[\\&|]/\\&/g'; };
client=$$(escape "$$OIDC_CLIENT_SECRET"); password=$$(escape "$$KEYCLOAK_BOOTSTRAP_PASSWORD");
sed -e "s|__OIDC_CLIENT_SECRET__|$$client|g" -e "s|__KEYCLOAK_BOOTSTRAP_PASSWORD__|$$password|g" /opt/keycloak/realm-template/developer-assistant-realm.json > /opt/keycloak/data/import/developer-assistant-realm.json;
exec /opt/keycloak/bin/kc.sh start-dev --import-realm''']
    web["services"]["web"]["environment"] = {"OIDC_INTERNAL_ISSUER": "http://keycloak:8080/realms/developer-assistant"}
    web["services"]["outline"]["environment"] = {
        "URL": url(c, "outline"), "FORCE_HTTPS": "true",
        "OIDC_AUTH_URI": url(c, "keycloak") + "/realms/developer-assistant/protocol/openid-connect/auth",
        "OIDC_LOGOUT_URI": url(c, "keycloak") + "/realms/developer-assistant/protocol/openid-connect/logout?client_id=developer-assistant-outline&post_logout_redirect_uri=" + quote(url(c, "outline"), safe="")}
    api["services"]["minio"]["environment"] = {"MINIO_BROWSER_REDIRECT_URL": url(c, "minio")}
    web["services"]["local-https"] = {
        "image": "caddy:2.10.2-alpine", "restart": "unless-stopped",
        "env_file": [str(STATE / "proxy.env")],
        "ports": [f"127.0.0.1:{p}:{p}" for p in sorted({c["hosts"][n]["port"] for n in selected(c)} | {c["grpc_port"]})],
        "volumes": [f"{STATE}/Caddyfile:/etc/caddy/Caddyfile:ro", f"{STATE}/certs/proxy:/certs:ro"],
        "networks": ["devassistant_net"],
    }
    # Compose recreates only the certificate consumers when a leaf identity changes.
    for service, name in ((neo, "neo4j"), (web["services"]["local-https"], "proxy")):
        certificate = STATE / "certs" / name / "cert.pem"
        if certificate.is_file():
            service["labels"] = {"devassistant.local-tls": hashlib.sha256(certificate.read_bytes()).hexdigest()}
    # SonarQube's private network is accessible only to the API-side service;
    # join the existing shared network for the optional browser proxy.
    if "sonarqube" in c["optional"]:
        api["services"]["sonarqube"] = {"networks": ["analyzer_private", "devassistant_net"]}
    for folder, document in (("api", api), ("web", web)):
        # JSON values are YAML-compatible; only port lists need a custom tag.
        lines = ["services:"]
        for name, service in document["services"].items():
            lines.append(f"  {name}:")
            for key, value in service.items():
                tag = "!override " if key == "ports" else ""
                lines.append(f"    {key}: {tag}" + json.dumps(value))
        owned_write(ROOT / folder / "docker-compose.override.yml", "\n".join(lines) + "\n")


def make_caddy(c: dict) -> None:
    lines = ["{", "  auto_https disable_redirects", "  admin off", "}"]
    for name in selected(c) + ["qdrant-grpc"]:
        host = c["hosts"]["qdrant" if name == "qdrant-grpc" else name]
        port = c["grpc_port"] if name == "qdrant-grpc" else host["port"]
        target = "h2c://qdrant:6334" if name == "qdrant-grpc" else SERVICES[name][0]
        lines += [f"https://{host['hostname']}:{port} {{", f"  tls /certs/cert.pem /certs/key.pem"]
        if name.startswith("qdrant"):
            lines += ["  @denied not header api-key {$QDRANT_PUBLIC_API_KEY}", '  respond @denied "API key required" 401']
        lines += [f"  reverse_proxy {target}", "}"]
    atomic(STATE / "Caddyfile", "\n".join(lines) + "\n")


def hosts_block(original: str, c: dict) -> str:
    begin, end = "# BEGIN DEVASSISTANT INSTALLER", "# END DEVASSISTANT INSTALLER"
    if (original.count(begin) != original.count(end) or original.count(begin) > 1
            or (begin in original and original.index(begin) > original.index(end))):
        raise ValueError("Malformed installer hosts block; repair /etc/hosts manually")
    clean = re.sub(re.escape(begin) + r".*?" + re.escape(end) + r"\n?", "", original, flags=re.S)
    names = sorted({c["hosts"][n]["hostname"] for n in selected(c)})
    # Refuse contradictory unowned mappings rather than relying on resolver order.
    for line in clean.splitlines():
        parts = line.split("#", 1)[0].split()
        if len(parts) > 1 and set(parts[1:]) & set(names) and parts[0] != "127.0.0.1":
            raise ValueError("A selected hostname already has a non-loopback hosts mapping")
    return clean.rstrip("\n") + "\n" + begin + "\n127.0.0.1 " + " ".join(names) + "\n" + end + "\n"
